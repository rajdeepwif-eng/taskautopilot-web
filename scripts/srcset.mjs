// Regenerates src/lib/srcset.ts from the webp pairs in src/assets/web/.
import { readdirSync, writeFileSync } from "node:fs";
const slugs = [...new Set(readdirSync("src/assets/web").filter((f) => /-(480|960)\.webp$/.test(f)).map((f) => f.replace(/-(480|960)\.webp$/, "")))].sort();
const v = (s, w) => "w_" + s.replace(/-/g, "_") + "_" + w;
const out = `// Generated by scripts/srcset.mjs — do not edit by hand.
${slugs.flatMap((s) => [480, 960].map((w) => `import ${v(s, w)} from "@/assets/web/${s}-${w}.webp";`)).join("\n")}
const ss = (a: [{ src: string }, number][]) => a.map(([i, w]) => i.src + " " + w + "w").join(", ");
export const SRCSET: Record<string, string> = {
${slugs.map((s) => `  "${s}": ss([[${v(s, 480)}, 480], [${v(s, 960)}, 960]]),`).join("\n")}
};
`;
writeFileSync("src/lib/srcset.ts", out);
console.log(slugs.length, "srcsets");
