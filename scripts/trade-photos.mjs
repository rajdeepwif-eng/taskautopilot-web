// Regenerates src/lib/tradePhotos.ts from the photos present in src/assets/trades/.
import { readdirSync, writeFileSync } from "node:fs";
const files = readdirSync("src/assets/trades").filter((f) => f.endsWith(".jpg")).sort();
const id = (f) => "p_" + f.replace(".jpg", "").replace(/-/g, "_");
const out = `// Generated by scripts/trade-photos.mjs — do not edit by hand.
import type { StaticImageData } from "next/image";
${files.map((f) => `import ${id(f)} from "@/assets/trades/${f}";`).join("\n")}

export const TRADE_PHOTOS: Record<string, StaticImageData> = {
${files.map((f) => `  "${f.replace(".jpg", "")}": ${id(f)},`).join("\n")}
};
`;
writeFileSync("src/lib/tradePhotos.ts", out);
console.log(files.length, "photos");
